export const COUNTRIES = RAW_COUNTRIES.map(([code, name]) => ({
  code,
  name,
  flag: flagEmoji(code),
})).sort((a, b) => a.name.localeCompare(b.name, "he"));

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function getCountry(code) {
  return BY_CODE.get(code) ?? { code: code ?? "", name: code ?? "לא ידוע", flag: "🏳️" };
}
